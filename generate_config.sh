#!/usr/bin/env bash

set -o pipefail

MAILCOW_PATH=/opt/mailcow-dockerized
MAILCOW_CONFIG_FILE="$MAILCOW_PATH/mailcow.conf"
OUTPUT_FILE=./conf/settings.ini
# Written here first and only moved over OUTPUT_FILE if the query worked, so
# a failing query (e.g. after a Mailcow schema change) keeps the old config.
TMP_FILE="$OUTPUT_FILE.tmp"

[ ! -f $MAILCOW_CONFIG_FILE ] && echo "Mailcow config not found. " && exit 1
source $MAILCOW_CONFIG_FILE
# Passed to the container by name, so the password stays out of ps
export MYSQL_PWD="$DBPASS"

# BEGIN SCRIPT
echo "# Autogenerated getmail config on $(date)" > "$TMP_FILE"
echo "[DEFAULT]" >> "$TMP_FILE"
echo "imap_debug:        False" >> "$TMP_FILE"
echo "imap_move_enable:  False" >> "$TMP_FILE"
echo "imap_move_folder:  getmail" >> "$TMP_FILE"
echo "imap_sync_folder:  INBOX" >> "$TMP_FILE"
echo "lmtp_hostname:     postfix-mailcow" >> "$TMP_FILE"
echo "lmtp_port:         25" >> "$TMP_FILE"
echo "lmtp_debug:        False" >> "$TMP_FILE"
echo "" >> "$TMP_FILE"

docker compose --project-directory "$MAILCOW_PATH" exec -T -e MYSQL_PWD mysql-mailcow mysql -u "$DBUSER" "$DBNAME" -B -N -e "
SELECT CONCAT_WS(CHAR(10),
  CONCAT('[JOB_' ,i.user2 ,'_' ,i.id ,']'),
  CONCAT('imap_hostname: ', s.host1), 
  CONCAT('imap_port: ', s.port1), 
  CONCAT('imap_ssl: ', IF(s.port1 = 993, 'True', 'False')), 
  CONCAT('imap_username: ', user1), 
  CONCAT('imap_password: ', password1), 
  CONCAT('lmtp_recipient: ', user2), 
  ''
)
FROM imapsync i JOIN imapsync_source s ON s.id = i.source_id
WHERE i.active = 0;
" | sed 's/\\n/\n/g' >> "$TMP_FILE"
rc=$?

# No job at all is treated as an error too: getmail would stop fetching mail.
if [ $rc -ne 0 ] || ! grep -q '^\[JOB_' "$TMP_FILE"; then
  echo "Query failed or returned no job, keeping $OUTPUT_FILE" >&2
  rm -f "$TMP_FILE"
  exit 1
fi
mv "$TMP_FILE" "$OUTPUT_FILE"
